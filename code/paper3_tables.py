"""Generate LaTeX tables for paper 3 directly from stats JSON + raw rows.

Outputs paper/causality/tables_auto.tex with \\newcommand macros so the
paper text never hard-codes numbers that can drift from data.

Run after paper3_analysis.py whenever data updates.
"""
import json
from pathlib import Path

import numpy as np


def fmt(v, nd=4):
    return f"{v:+.{nd}f}" if isinstance(v, (int, float)) else "---"


def main():
    repo = Path(__file__).resolve().parent.parent
    stats = json.load(open(repo / "results/paper3_stats.json"))

    e1, e3, e2 = stats["e1"], stats["e3"], stats["e2"]
    L = []
    L.append("% Auto-generated by code/paper3_tables.py -- DO NOT EDIT NUMBERS BY HAND\n"
             "% NOTE: macro names must be LaTeX-safe (no digits in prefix);\n"
             "% architecture keys are mapped below.\n")

    # --- macros for inline numbers ---
    macros = {
        "eOneBaseR": f"{e1['base']['pearson_r']:+.2f}",
        "eOneBaseSlope": f"{e1['base']['slope']:+.4f}",
        "eOneGeoShare": f"{e1['geometric_share']['share_pct']:.1f}\\%",
        "anisoDc": f"{e1['aniso2']['dc100_median'] * 100:.1f}",
        "anisoDidp": f"{e1['aniso2']['didp_median'] * 100:.1f}",
        "anisoRelD": f"{e1['aniso2']['relD_max'] * 100:.0f}",
        "isoDc": f"{e1['iso2']['dc100_median'] * 100:.1f}",
        "isoDd": f"{e1['iso2']['dD_median']:+.1f}",
        "rotMaxDc": f"{e1['rotate']['dc100_max_abs'] * 100:.1f}",
        "rotMaxDd": f"{e1['rotate']['dD_max_abs']:.2f}",
        "recZeroDc": f"{e1['recolor0']['dc100_median'] * 100:+.1f}",
        "eThreeDc": f"{e3['train_whiten_dc100']['median'] * 100:+.1f}",
        "eThreeP": f"{e3['train_whiten_dc100']['wilcoxon_p']:.3f}",
        "eThreePosN": str(e3["train_whiten_dc100"]["pos"]),
        "eThreeInferP": f"{e3['inference_recolor_dfc']['wilcoxon_p']:.3f}",
    }
    for arch, d in e2.items():
        if d.get("status") != "complete":
            continue
        # LaTeX-safe short name: resnet34->rB (B=34 is digits; use letters)
        name_map = {"resnet18": "rA", "resnet34": "rB", "resnet50": "rC",
                    "shufflenet_v2_x1_0": "sfn", "regnet_y_400mf": "rg"}
        key = name_map.get(arch, arch[:4])
        macros[f"{key}BaseR"] = f"{d['base']['pearson_r']:+.2f}"
        macros[f"{key}BaseSlope"] = f"{d['base']['slope']:+.4f}"
        macros[f"{key}GeoShare"] = f"{d['recolor_share_pct']:.1f}\\%"
        if d.get("aniso2_dc100_median") is not None:
            macros[f"{key}AnisoDc"] = f"{d['aniso2_dc100_median'] * 100:.1f}"
    L.append("\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()))

    # --- E3 paired table ---
    rows = json.load(open(repo / "runs/v2_e3.json"))["rows"]
    e3d = {r["model"]: r for r in rows if r["arm"] == "e3"}
    e3c = {r["model"]: r for r in rows if r["arm"] == "e3c"}
    L.append("\n\n% E3 paired table\n\\newcommand{\\eThreePairedTable}{%\n"
             "\\begin{tabular}{@{}lccccc@{}}\n\\hline\n"
             "Model & $c_{100}^{\\mathrm{w}}$ & $c_{100}^{\\mathrm{ctrl}}$ & "
             "$\\Delta c_{100}$ & $\\Delta$ id-probe & $\\Delta$ head (inf.) \\\\\n\\hline\n")
    for m in sorted(e3d):
        a, b = e3d[m], e3c[m]
        dc = a["c100_probe"] - b["c100_probe_ctrl"]
        dip = a["id_probe_acc"] - b["id_probe_acc"]
        dinf = a["id_fc_acc_inference_recolor"] - b["id_fc_acc_orig"]
        # LaTeX-safe model label: replace '_' with '\_'
        short = (m.replace("resnet18_", "")
                  .replace("wd", "w").replace("lr", "l")
                  .replace("_", "\\_"))
        L.append(f"{{\\tt {short}}} & {a['c100_probe']:.3f} & {b['c100_probe_ctrl']:.3f} & "
                 f"{dc * 100:+.1f} & {dip * 100:+.1f} & {dinf * 100:+.1f} \\\\\n")
    L.append("\\hline\n\\end{tabular}}\n")

    # --- E1 endpoint table (appendix B) ---
    rows = json.load(open(repo / "runs/v2_e1_full.json"))["rows"]
    models = sorted({r["model"] for r in rows})
    L.append("\n% E1 endpoint table\n\\newcommand{\\eOneEndpointTable}{%\n"
             "\\begin{tabular}{@{}lccc@{}}\n\\hline\n"
             "Model & \\aniso$(2)$ $\\Delta c_{100}$ & "
             "\\isot$(2)$ $\\Delta c_{100}$ & "
             "\\recolor$(0)$ $\\Delta c_{100}$ \\\\\n\\hline\n")
    for m in models:
        pts = {r["kind"] + ("" if r["param"] is None else str(r["param"])): r
               for r in rows if r["model"] == m}
        b = pts["base"]
        a2 = pts["gauss_aniso2.0"]
        i2 = pts["gauss_iso2.0"]
        r0 = pts["recolor0.0"]
        short = (m.replace("resnet18_", "").replace("wd", "w")
                  .replace("lr", "l").replace("_", "\\_"))
        L.append(f"{{\\tt {short}}} & {(a2['c100_probe']-b['c100_probe'])*100:+.1f} & "
                 f"{(i2['c100_probe']-b['c100_probe'])*100:+.1f} & "
                 f"{(r0['c100_probe']-b['c100_probe'])*100:+.1f} \\\\\n")
    L.append("\\hline\n\\end{tabular}}\n")

    out = repo / "paper/causality/tables_auto.tex"
    # LF-only endings: tectonic chokes on \r after \\ inside tabular
    out.write_bytes("".join(L).replace("\r\n", "\n").encode("utf-8"))
    print(f"written {out} ({len(L)} lines)")


if __name__ == "__main__":
    main()
